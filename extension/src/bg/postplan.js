/** Сколько сообщений будет в ветке этого формата. */
export function partsFor(kind, rand = Math.random) {
  const p = POST_KINDS[kind]?.parts ?? 1;
  if (typeof p === 'number') return p;
  const [lo, hi] = p;
  return lo + Math.floor(rand() * (hi - lo + 1));
}


/** Часы и минуты в московском поясе. Публикуем по времени аудитории, а не машины. */
export function moscowNow(date = new Date()) {
  const s = new Intl.DateTimeFormat('ru-RU', {
    timeZone: 'Europe/Moscow',
    hour: '2-digit', minute: '2-digit', day: '2-digit', month: '2-digit', year: 'numeric',
    hour12: false,
  }).formatToParts(date);

  const get = (t) => Number(s.find((p) => p.type === t)?.value || 0);
  return {
    hour: get('hour'), minute: get('minute'),
    day: get('day'), month: get('month'), year: get('year'),
    key: `${get('year')}-${String(get('month')).padStart(2, '0')}-${String(get('day')).padStart(2, '0')}`,
    minutes: get('hour') * 60 + get('minute'),
  };
}

/**
 * Слоты на сутки: от начала окна с заданным шагом.
 *
 * Возвращаются минуты от полуночи, чтобы сравнение не зависело от даты.
 */
export function daySlots(posting, dayKey = null) {
  const from = Math.max(0, Math.min(23, posting.windowFromHour ?? 9));
  const to = Math.max(from + 1, Math.min(24, posting.windowToHour ?? 23));

  /*
   * Если задан коридор публикаций на день, расписание строится от него, а не
   * от шага.
   *
   * Прежняя механика раскладывала слоты через фиксированный промежуток, и день
   * получался одинаковым: в семь утра первый пост, дальше каждые полчаса до
   * ночи — из недели в неделю один и тот же ритм. Для аккаунта, который хочет
   * выглядеть человеком, ровный ритм хуже частоты: человек в один день пишет
   * шесть раз, в другой одиннадцать.
   *
   * Число на сутки выводится из даты, а не разыгрывается: оно обязано
   * пережить перезапуск браузера, иначе после каждого выката расписание
   * пересобиралось бы заново, а уже опубликованные слоты означали бы не то же
   * самое, что вчера.
   */
  const quota = dayQuota(posting, dayKey);
  if (quota) {
    const span = (to - from) * 60;
    const step = span / quota;
    const out = [];
    /* Слот ставится в середину своей доли окна: так первый пост не выпадает
       ровно на открытие окна, а последний — на его закрытие. */
    for (let i = 0; i < quota; i++) out.push(Math.round(from * 60 + step * (i + 0.5)));
    return out;
  }

  const step = Math.max(MIN_STEP_MIN, (posting.intervalHours ?? 3) * 60);

  const out = [];
  for (let m = from * 60; m <= to * 60 - 1 && out.length < MAX_SLOTS; m += step) out.push(m);
  return out;
}

/**
 * Сколько публикаций в этот конкретный день.
 *
 * Ноль означает «коридор не задан» — тогда работает прежнее расписание с
 * фиксированным шагом. Число детерминировано по дате: см. `daySlots`.
 */
export function dayQuota(posting, dayKey = null) {
  const min = posting?.perDayMin ?? 0;
  const max = posting?.perDayMax ?? 0;
  if (!min || !max || max < min) return 0;

  const key = dayKey || moscowNow().key;
  let h = 2166136261;
  const s = `posts#${key}`;
  for (let i = 0; i < s.length; i++) { h ^= s.charCodeAt(i); h = Math.imul(h, 16777619); }

  return Math.min(MAX_SLOTS, min + ((h >>> 0) % (max - min + 1)));
}

/**
 * Почему у шага есть жёсткий минимум и почему он именно такой.
 *
 * Публикация — самое заметное действие аккаунта, и два поста подряд с
 * промежутком в пять минут читаются как бот однозначнее, чем сорок постов,
 * разложенных по дню. Двадцать минут — нижняя граница, при которой лента
 * профиля ещё выглядит как человек, который весь день что-то дописывает.
 *
 * Потолок числа слотов раньше стоял 24 и молча срезал любое расписание частотой
 * плотнее часа: при шаге в полчаса окно 7:00–24:00 даёт тридцать четыре слота,
 * а до правки их оставалось двадцать четыре. Настройка «до пятидесяти постов»
 * при этом выглядела бы применённой.
 */
const MIN_STEP_MIN = 20;
const MAX_SLOTS = 60;

/**
 * Сдвиг слота на сегодня.
 *
 * Разброс детерминированный: он выводится из даты и номера слота, а не
 * разыгрывается заново на каждой проверке. Иначе смещение прыгало бы при каждом
 * тике и слот то наступал, то переставал.
 */
export function slotJitter(dayKey, index, jitterMin = 30) {
  if (jitterMin <= 0) return 0;
  let h = 2166136261;
  const s = `${dayKey}#${index}`;
  for (let i = 0; i < s.length; i++) { h ^= s.charCodeAt(i); h = Math.imul(h, 16777619); }
  const unit = ((h >>> 0) % 2000) / 1000 - 1;   // -1..1
  return Math.round(unit * jitterMin);
}

/**
 * Окно слота: когда он наступает и когда закрывается окончательно.
 *
 * Хвост окна упирается не только в `graceMin`, но и в следующий слот, и это не
 * перестраховка. При квоте в одиннадцать постов шаг — полтора часа, а разброс
 * ±25 минут сводит соседние слоты до сорока трёх, то есть теснее окна догона.
 * Без упора агент опубликовал бы поздний слот (перебор идёт с конца), а
 * следующим тиком догнал бы ранний — два поста с разницей в пять минут. Один
 * пропущенный слот дешевле такой пары.
 */
function slotWindow(posting, dayKey, slots, i) {
  const jitter = posting.jitterMin ?? 30;
  const at = slots[i] + slotJitter(dayKey, i, jitter);
  const next = i + 1 < slots.length
    ? slots[i + 1] + slotJitter(dayKey, i + 1, jitter)
    : Infinity;

  return { at, until: Math.min(at + (posting.graceMin ?? 75), next) };
}

/** Дневной потолок публикаций: коридор на сутки, но не выше предохранителя. */
function dayCap(posting, dayKey) {
  return Math.min(posting.perDay ?? 5, dayQuota(posting, dayKey) || Infinity);
}

/**
 * Пора ли публиковать.
 *
 * Слот считается наступившим, если его сдвинутое время уже прошло, но окно ещё
 * не закрылось. Просроченные слоты намеренно не догоняются: если агент был
 * выключен полдня, при возвращении не должно вылететь четыре поста подряд.
 *
 * @returns {{due: boolean, slot?: number, why?: string}}
 */
export function slotDue(posting, state, now = new Date()) {
  const t = moscowNow(now);
  const posted = state.postedSlots?.[t.key] || [];

  if (!posting.enabled) return { due: false, why: 'автопостинг выключен' };

  /*
   * Свои посты — не с первого дня.
   *
   * Собственная публикация заметнее любого комментария: её видят подписчики,
   * она попадает в ленты, к ней прикладываются картинка и ссылки. Аккаунту,
   * который только вернулся после ограничения, первые дни лучше провести
   * читателем и собеседником. Отсчёт идёт от того же дня, что и прогрев
   * комментариев, — от `restartDate`, если он есть.
   */
  const startAfter = posting.startAfterDay || 0;
  if (startAfter > 0) {
    const day = daysSince(state.restartDate || state.firstRunDate);
    if (day < startAfter) {
      return { due: false, why: `свои посты с ${startAfter}-го дня, идёт ${day}-й` };
    }
  }

  /* Коридор на сутки — это и есть план дня; `perDay` остаётся предохранителем
     сверху, на случай ручных запусков и догона. */
  const perDay = dayCap(posting, t.key);
  if (posted.length >= perDay) return { due: false, why: `дневной лимит ${perDay} исчерпан` };

  const slots = daySlots(posting, t.key);

  for (let i = slots.length - 1; i >= 0; i--) {
    if (posted.includes(i)) continue;
    const { at, until } = slotWindow(posting, t.key, slots, i);
    if (t.minutes >= at && t.minutes <= until) return { due: true, slot: i, lateMin: t.minutes - at };
  }

  return { due: false, why: 'до следующего слота ещё рано' };
}

/**
 * Слоты, чьё окно закрылось без публикации.
 *
 * Потеря слота — не авария, а обычное следствие того, что расписание живёт
 * отдельно от сессий: пост пишется только внутри сессии, а окно слота может
 * целиком лечь в перерыв. Но происходить это должно вслух. 03.08 так пропал
 * разбор инструмента в 16:40 — журнал не сказал ни слова, и заметить пропажу
 * можно было только пересчётом расписания задним числом.
 *
 * Уже названные пропуски отсекаются по `missedSlots`: проверка идёт на каждом
 * тике, а запись в журнале нужна одна.
 *
 * @returns {Array<{slot: number, at: number, until: number, lateMin: number}>}
 */
export function expiredSlots(posting, state, now = new Date()) {
  if (!posting?.enabled) return [];

  const t = moscowNow(now);
  const posted = state.postedSlots?.[t.key] || [];
  const told = state.missedSlots?.[t.key] || [];

  /* Потолок закрыл публикации осознанно — это не потеря, и в журнале ей не место. */
  if (posted.length >= dayCap(posting, t.key)) return [];

  const slots = daySlots(posting, t.key);
  const out = [];

  for (let i = 0; i < slots.length; i++) {
    if (posted.includes(i) || told.includes(i)) continue;
    const { at, until } = slotWindow(posting, t.key, slots, i);
    if (t.minutes > until) out.push({ slot: i, at, until, lateMin: t.minutes - at });
  }

  return out;
}

/**
 * Слоты, отданные под полезный разбор.
 *
 * Обещание «дважды в день полезный пост» не может зависеть от розыгрыша
 * форматов: при доле в общем мешке такой пост в один день выйдет трижды, в
 * другой не выйдет вовсе, и обещание превращается в лотерею. Поэтому у него
 * не доля, а места в расписании.
 *
 * Места выбираются не подряд: два разбора в соседние слоты — это полтора часа
 * инструкций и потом день без них. Четверть и две трети дня разносят их на
 * утро и вечер при любой дневной квоте — от шести слотов до одиннадцати.
 */
export function guideSlots(posting, dayKey = null) {
  const want = Math.max(0, posting?.guidesPerDay ?? 0);
  if (!want) return new Set();

  const slots = daySlots(posting, dayKey);
  if (slots.length < 2) return new Set(slots.length ? [0] : []);

  const at = [0.25, 0.68, 0.45, 0.85]
    .slice(0, want)
    .map((share) => Math.min(slots.length - 1, Math.round(share * (slots.length - 1))));

  return new Set(at);
}

/** Когда ближайший слот — для интерфейса и журнала. */
export function nextSlotIn(posting, state, now = new Date()) {
  const t = moscowNow(now);
  const posted = state.postedSlots?.[t.key] || [];
  const slots = daySlots(posting, t.key);

  for (let i = 0; i < slots.length; i++) {
    if (posted.includes(i)) continue;
    const at = slots[i] + slotJitter(t.key, i, posting.jitterMin ?? 30);
    if (at > t.minutes) return { minutes: at - t.minutes, slot: i };
  }
  // Сегодня всё; первый слот завтра.
  const first = slots[0] + slotJitter(t.key, 0, posting.jitterMin ?? 30);
  return { minutes: 24 * 60 - t.minutes + first, slot: 0, tomorrow: true };
}

/* --------------------------------- Формат --------------------------------- */

/**
 * Выбрать формат следующего поста.
 *
 * Веса из `POST_KINDS`, но с двумя поправками. Формат, вышедший последним, в
 * розыгрыш не идёт вовсе — два наблюдения подряд читаются как одно длинное.
 * Формат, требующий материала, отбрасывается, если материала нет: молчать
 * лучше, чем писать новость ни о чём.
 */
export function pickKind(state, {
  hasMaterial = true, rand = Math.random, settings = null, stats = null,
} = {}) {
  const last = state.lastPostKind || null;
  const recent = (state.recentPostKinds || []).slice(-4);

  /*
   * Мешок стал дробным.
   *
   * Раньше вес был целым числом и формат клался в мешок столько раз, сколько
   * весил. С появлением множителя обучения веса перестали быть целыми: 3 × 1.37
   * это 4.11, и округление съедало бы ровно то, ради чего множитель считался.
   * Поэтому выбор идёт по накопленной сумме — обычная рулетка.
   */
  const pool = [];
  let total = 0;

  for (const [key, k] of Object.entries(POST_KINDS)) {
    if (key === last) continue;
    if (k.needsMaterial && !hasMaterial) continue;

    // Чем чаще формат выходил недавно, тем меньше его шанс.
    const used = recent.filter((r) => r === key).length;
    let weight = Math.max(1, k.share - used);

    /*
     * Поправка по фактическому отклику. Единица, пока данных мало, и всегда в
     * пределах коридора: заданные веса несут редакторское решение, а не только
     * «что заходит», и стирать его данными нельзя.
     */
    if (settings && stats) weight *= learnedFactor(key, stats, settings);

    total += weight;
    pool.push({ key, upTo: total });
  }

  if (!pool.length || total <= 0) {
    const any = Object.entries(POST_KINDS)
      .filter(([, k]) => !k.needsMaterial || hasMaterial)
      .map(([key]) => key);
    return any[0] || 'tip';
  }

  const roll = rand() * total;
  return (pool.find((p) => roll < p.upTo) || pool[pool.length - 1]).key;
}

/* ---------------------------------- Тема ---------------------------------- */

/**
 * Какую тему поставить посту.
 *
 * Тема в Threads — это не хэштег, а отдельное поле рядом с именем автора, и
 * выбранная тема открывает ленту, которую можно листать. Для аккаунта, у
 * которого девятнадцать подписчиков, это вторая поверхность раздачи после
 * ленты подписок.
 *
 * **Берём из `niche.tags`, а не выдумываем.** Список тем в настройках уже
 * проверен живым Threads поштучно: каждая отдаёт по 18–20 карточек, почти все
 * русскоязычные. Тема, которой в Threads нет, открывает пустую ленту — пользы
 * от неё ноль, а выглядит как выдумка.
 *
 * **Предпочитаем ту, о которой пост и написан.** Совпадение ищется по корню:
 * тема «нейросети» подходит посту про нейросеть, а «claude» — посту про Claude
 * Code. Из нескольких совпавших берётся самая длинная: она точнее.
 *
 * **Не повторяем подряд.** Профиль, где у пяти постов кряду одна тема,
 * читается как лента одного бота, да и раздача от повтора ничего не выигрывает.
 *
 * @returns {string|null} тема либо null, если ставить нечего
 */
export function pickTopic(text, settings, state = {}, rand = Math.random) {
  const tags = (settings?.niche?.tags || []).map((t) => String(t || '').trim()).filter(Boolean);
  if (!tags.length) return null;

  const recent = (state.recentTopics || []).slice(-2).map((t) => t.toLowerCase());
  const hay = String(text || '').toLowerCase().replace(/ё/g, 'е');

  /* Корень темы: «нейросети» → «нейросет», чтобы поймать все падежи. */
  const root = (t) => {
    const s = t.toLowerCase().replace(/ё/g, 'е');
    return s.length > 5 ? s.slice(0, Math.max(5, s.length - 2)) : s;
  };

  const matched = tags
    .filter((t) => hay.includes(root(t)))
    .sort((a, b) => b.length - a.length);

  const fresh = matched.filter((t) => !recent.includes(t.toLowerCase()));
  if (fresh.length) return fresh[0];

  /*
   * По тексту не совпало ничего — берём случайную из общих, но всё равно не
   * ту, что была только что. Пустая тема лучше неточной лишь на первый взгляд:
   * пост без темы не попадает вообще никуда, а «технологии» на посте про
   * агентов — это неточно, но не ложно.
   */
  const pool = tags.filter((t) => !recent.includes(t.toLowerCase()));
  const from = pool.length ? pool : tags;
  return from[Math.floor(rand() * from.length)] || null;
}

/** Запомнить поставленную тему — для защиты от повтора подряд. */
export function rememberTopic(state, topic) {
  if (!topic) return state;
  state.recentTopics = [...(state.recentTopics || []), topic].slice(-6);
  return state;
}

/** Отметка слота по дням. Больше трёх дней истории не нужно никому. */
function rememberSlot(map, dayKey, slot) {
  const next = { ...(map || {}) };
  next[dayKey] = [...new Set([...(next[dayKey] || []), slot])];

  const keys = Object.keys(next).sort().slice(-3);
  const trimmed = {};
  for (const k of keys) trimmed[k] = next[k];
  return trimmed;
}

/**
 * Записать, что о потерянном слоте уже сказано.
 *
 * Отдельно от `postedSlots`, а не отметкой в нём: по числу отработанных слотов
 * считается дневной потолок, и пропуск, записанный туда, урезал бы остаток дня
 * за компанию.
 */
export function markSlotMissed(state, slot, now = new Date()) {
  state.missedSlots = rememberSlot(state.missedSlots, moscowNow(now).key, slot);
  return state;
}

/** Записать, что слот отработан. Хранится по дням, старое подрезается. */
export function markSlotPosted(state, slot, kind, now = new Date()) {
  const t = moscowNow(now);

  state.postedSlots = rememberSlot(state.postedSlots, t.key, slot);
  state.lastPostKind = kind;
  state.recentPostKinds = [...(state.recentPostKinds || []), kind].slice(-8);
  return state;
}

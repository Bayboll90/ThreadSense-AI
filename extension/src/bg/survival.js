/**
 * Выживаемость опубликованных комментариев.
 *
 * Проверка сразу после отправки отвечает на вопрос «дошло ли». Она нужна, но
 * отвечает не на тот вопрос, который в итоге важнее: **осталось ли**.
 *
 * Случай, ради которого это написано. Комментарий у `@reader_example`
 * прошёл проверку в момент публикации — агент нашёл свой текст среди карточек
 * ветки. Через два часа его в ветке не было. Мгновенная проверка не соврала:
 * ответ существовал. Он исчез позже, и об этом агент не узнал бы никогда.
 *
 * Исчезновение через час — куда более надёжный признак ограничения, чем
 * отсутствие сразу: при теневом ограничении публикация обычно проходит, и
 * первая проверка её подтверждает.
 *
 * Различать причины исчезновения мы не можем и не пытаемся: автор мог удалить
 * ответ, платформа могла снять его фильтром, ветку могли закрыть. Единичный
 * случай ничего не значит и намеренно не считается тревогой. Значение имеет
 * серия: если пропадает подряд, писать дальше бессмысленно.
 */

/**
 * Записать опубликованный комментарий для будущей проверки.
 *
 * Храним начало текста, а не весь: для поиска в ветке хватает, а состояние
 * пишется в storage на каждом шаге, и лишние килобайты там ни к чему.
 */
export function recordPublished(state, { url, postId, text, author }, now = Date.now()) {
  if (!url || !text) return state;

  const entry = {
    url,
    postId: postId || null,
    author: author || null,
    needle: String(text).slice(0, 90),
    at: now,
    checkedAt: null,
    alive: null,
  };

  state.published = [...(state.published || []).filter((p) => p.url !== url), entry].slice(-40);
  return state;
}

/**
 * Что проверить прямо сейчас, если пора.
 *
 * Условий четыре. Ответу дают отлежаться: свежий и так только что подтверждён,
 * а исчезает он позже. Между проверками держим паузу: перепроверка стоит
 * перехода на страницу ветки. Каждый ответ проверяем один раз — второй раз он
 * расскажет то же самое. И берём **самый свежий** из подошедших, а не самый
 * старый.
 *
 * Последнее — не мелочь, а исправление живого дефекта. Очередь непроверенных
 * не может опустеть: агент публикует 28–45 комментариев в сутки, а проверить
 * успевает не больше двадцати (одна проверка в пятьдесят минут на окне 7–24).
 * Разница копится, и выбор самого старого означает, что смотреть всегда будут
 * на край очереди. Замер 04.08: под наблюдением сорок ответов, проверен один —
 * опубликованный **сорок один час назад** при замысле «через сорок минут».
 * Двадцать два непроверенных из тридцати девяти были старше суток.
 *
 * Отсюда же верхняя граница возраста. Пропажа комментария через час — сигнал;
 * его отсутствие через сутки не значит почти ничего: автор мог удалить, ветку
 * могли снять, выдача могла перестроиться. Считать это уликой теневого
 * ограничения и останавливать по ней агента — значит останавливаться на шуме.
 */
export function pickForRecheck(state, settings, now = Date.now()) {
  const s = settings.safety || {};
  if (s.recheckEnabled === false) return null;

  const after = (s.recheckAfterMin ?? 45) * 60000;
  const maxAge = (s.recheckMaxAgeMin ?? 240) * 60000;
  const every = (s.recheckEveryMin ?? 60) * 60000;

  if (now - (state.lastRecheckAt || 0) < every) return null;

  const ready = (state.published || [])
    .filter((p) => p.checkedAt == null)
    .filter((p) => now - p.at >= after && now - p.at <= maxAge)
    // Самый свежий из подошедших: он ближе всего к задуманному окну.
    .sort((a, b) => b.at - a.at);

  return ready[0] || null;
}

/**
 * Закрыть ответы, смотреть которые уже поздно.
 *
 * Без этого они висят в наблюдении «непроверенными» до вытеснения из сорока
 * записей, и сводка врёт: тридцать девять ждущих проверки выглядят работой,
 * которая вот-вот случится, тогда как случиться она уже не может.
 *
 * Исход у них — `null`, «не проверяли»: серию такой ответ не двигает ни в одну
 * сторону. Отметка `expired` оставлена, чтобы в сводке было видно разницу
 * между «смотрели и не нашли» и «смотреть не стали».
 *
 * @returns {number} сколько записей закрыто
 */
export function expireStale(state, settings, now = Date.now()) {
  let n = 0;
  state.published = (state.published || []).map((p) => {
    if (!isStale(p, settings, now)) return p;
    n++;
    return { ...p, checkedAt: now, alive: null, expired: true };
  });

  return n;
}

/** Сколько записей просрочено. Считается без записи в хранилище. */
export function staleCount(state, settings, now = Date.now()) {
  return (state.published || []).filter((p) => isStale(p, settings, now)).length;
}

function isStale(p, settings, now) {
  if (p.checkedAt != null) return false;
  const maxAge = (settings.safety?.recheckMaxAgeMin ?? 240) * 60000;
  return now - p.at > maxAge;
}

/**
 * Учесть исход проверки.
 *
 * Счётчик растёт только на пропажах подряд: один исчезнувший ответ — обычное
 * дело, автор мог его удалить. Живой ответ обнуляет счётчик, потому что серия
 * прервалась.
 *
 * Исходов три, и третий обязателен. `alive === null` значит «посмотреть не
 * вышло»: ветка отдала не все ответы, и отсутствия нашего среди показанных
 * недостаточно, чтобы называть его пропажей. Такая проверка не двигает серию
 * ни в одну сторону — ни растит, ни обнуляет. Раньше `null` попадал в ветку
 * «не жив» и считался пропажей наравне с настоящей: три подряд — и агент
 * вставал, ничего толком не проверив.
 */
export function recordRecheck(state, url, alive, now = Date.now()) {
  const outcome = alive === true ? true : (alive === false ? false : null);

  state.published = (state.published || []).map((p) => (
    p.url === url ? { ...p, checkedAt: now, alive: outcome } : p
  ));
  state.lastRecheckAt = now;

  if (outcome === true) state.vanished = 0;
  else if (outcome === false) state.vanished = (state.vanished || 0) + 1;

  return state;
}

/**
 * Пора ли останавливаться.
 *
 * Порог намеренно выше, чем у неподтверждённых публикаций: там речь о сбое,
 * который виден сразу, здесь — о чужих решениях, которые к нам могут не иметь
 * отношения вовсе.
 */
export function shouldHalt(state, settings) {
  const limit = settings.safety?.vanishedLimit ?? 3;
  return (state.vanished || 0) >= limit;
}

/**
 * Забыть серию, которая уже сработала.
 *
 * Серия, набравшая предел, обязана была превратиться в остановку. Если
 * остановки нет — значит она уже кончилась: истёк срок, её сняли руками или
 * она оказалась неисправной. Оставлять при этом счётчик на пределе значит
 * превращать паузу в бесконечную: первая же следующая пропажа снова остановит
 * агента, и так по кругу, без единой новой серии. Пауза для того и нужна,
 * чтобы после неё считать заново.
 *
 * Ровно это вышло 04.08: неисправную остановку сняли, а `vanished` остался
 * равен трём — агент вернулся к работе на волосок от следующей остановки.
 *
 * @returns {boolean} была ли серия сброшена — чтобы сказать об этом в журнале
 */
export function releaseSpentStreak(state, settings) {
  if (state.halt) return false;
  if (!shouldHalt(state, settings)) return false;

  state.vanished = 0;
  state.consecutiveShadowFails = 0;
  return true;
}

/**
 * Сводка для журнала и интерфейса.
 *
 * Пропажи считаются по подтверждённым, а не вычитанием живых из проверенных:
 * с появлением третьего исхода разница между ними — это ещё и те, кого не
 * вышло посмотреть, и записывать их в пропавшие значит пугать себя цифрой,
 * за которой ничего нет.
 */
export function survivalStats(state) {
  const all = state.published || [];
  const checked = all.filter((p) => p.checkedAt != null);

  return {
    tracked: all.length,
    checked: checked.length,
    alive: checked.filter((p) => p.alive === true).length,
    vanished: checked.filter((p) => p.alive === false).length,
    unknown: checked.filter((p) => p.alive == null).length,
    streak: state.vanished || 0,
  };
}

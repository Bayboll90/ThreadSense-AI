/** Слова короче этого темой быть не могут. Латиница исключена: gpt, mcp, ai. */
const MIN_TERM_LEN = 4;

/**
 * Значимые слова текста.
 *
 * Кроме одиночных слов берутся и пары соседних: «claude code», «контекстное
 * окно», «vision pro». По отдельности половина таких слов ничего не значит, а
 * пара называет тему точно. Пара при этом не заменяет одиночные слова, а
 * добавляется к ним — иначе всплеск размажется по десятку разных сочетаний с
 * одним и тем же ядром.
 */
export function termsOf(text) {
  const words = normalize(text).split(' ').filter(Boolean);
  const kept = [];
  const out = new Set();

  for (const w of words) {
    const short = w.length < MIN_TERM_LEN && !/^[a-z0-9]+$/.test(w);
    if (STOP.has(w) || short || w.length < 2) { kept.push(null); continue; }
    // Голое число темой не бывает: «2026», «100», номера версий без имени.
    if (/^\d+$/.test(w)) { kept.push(null); continue; }
    kept.push(w);
    out.add(w);
  }

  for (let i = 0; i + 1 < kept.length; i++) {
    if (kept[i] && kept[i + 1]) out.add(`${kept[i]} ${kept[i + 1]}`);
  }

  return [...out];
}


/**
 * Что обсуждают в нише прямо сейчас.
 *
 * Зачем понадобилось. Материал для собственных постов брался только из RSS —
 * сорок три фида, Google News, Hacker News. Это отвечает на вопрос «что
 * произошло в мире», но не на вопрос «о чём говорят здесь». За неделю работы
 * профиль не набрал ни одного отклика, и разведка в браузере показала почему:
 * агент писал аккуратные экспертные утверждения о новостях, которых в ленте
 * Threads никто не обсуждал, а отклик в нише собирали посты про то, что в этой
 * ленте кипело прямо в тот час.
 *
 * Откуда берутся данные. Ниоткуда дополнительно: агент и так сканирует ленту и
 * поиск, выбирая цель для комментария. Прежде вся эта выборка выбрасывалась
 * после того, как из неё вынули одного кандидата. Теперь она копится здесь —
 * бесплатно, без единого запроса к модели и без единого лишнего перехода.
 *
 * Что считается трендом. Не «много лайков»: у поста с тысячей лайков за неделю
 * скорость набора ниже, чем у поста с полусотней за час, а нам нужно попасть в
 * разговор, пока он идёт. Поэтому тема оценивается по двум числам сразу:
 *
 *   **жар**   — сумма скоростей набора реакций у постов на эту тему;
 *   **всплеск** — во сколько раз доля темы в свежем окне выше её же доли в
 *                 предыдущем.
 *
 * Одного жара мало: «нейросети» — самая горячая тема ниши всегда, и писать
 * каждый раз про нейросети вообще бессмысленно. Одного всплеска тоже мало:
 * случайное слово из одного поста даёт бесконечный всплеск на пустом месте.
 * Значение имеет произведение — тема, которая и заметна, и выросла.
 *
 * Всё локально. Ни одного токена: разбор текста, частоты, сравнение окон.
 */


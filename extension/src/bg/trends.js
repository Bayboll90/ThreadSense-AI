/** Вес реакции. Ответ дороже лайка: он требует усилия и тянет ветку вверх. */
export function reactionScore(p) {
  return (p.likes || 0) + 3 * (p.replies || 0) + 5 * (p.reposts || 0);
}

/**
 * Скорость набора реакций, очков в час.
 *
 * Два способа, и первый честнее. Если пост попался нам дважды, у нас есть
 * настоящий прирост за настоящий промежуток — это измерение, а не оценка.
 * Возраст, показанный Threads, огрублён до «2 ч» и «вчера», и деление на него
 * даёт ошибку в разы у всего, что старше суток.
 *
 * Тот же урок, что и с полем ввода: спрашивать объект, а не свою модель о нём.
 * Здесь объект отвечает только при повторной встрече, поэтому запасной путь
 * остаётся — но он именно запасной.
 */
export function velocityOf(o, now = Date.now()) {
  const spanH = (o.lastAt - o.firstAt) / 3.6e6;
  if (spanH >= 0.33 && o.lastScore > o.firstScore) {
    return (o.lastScore - o.firstScore) / spanH;
  }
  const ageH = Math.max(0.5, (o.ageMinutes ?? 60) / 60 + (now - o.lastAt) / 3.6e6);
  return o.lastScore / ageH;
}

const MAX_OBSERVATIONS = 400;

/**
 * Записать увиденное.
 *
 * Пост, встреченный повторно, не дублируется и не перезаписывается целиком:
 * сохраняется первый снимок счётчиков и обновляется последний. Ради этого всё
 * и затевалось — разница между ними и есть прирост.
 *
 * @param {object}   state
 * @param {object[]} posts  карточки как их отдаёт разбор ленты
 */
export function observe(state, posts, settings, now = Date.now()) {
  const keepMs = (settings?.trends?.windowHours ?? 48) * 3.6e6;
  const byId = new Map();
  for (const o of state.observations || []) byId.set(o.id, o);

  let fresh = 0;
  let updated = 0;

  for (const p of posts || []) {
    if (!p?.id) continue;
    const score = reactionScore(p);
    const prev = byId.get(p.id);

    if (prev) {
      // Счётчики не убывают. Меньшее значение означает, что счётчик не
      // прочитался, а не что лайки сняли — принимать его за прирост нельзя.
      if (score >= prev.lastScore) {
        prev.lastScore = score;
        prev.lastAt = now;
        prev.likes = p.likes ?? prev.likes;
        prev.replies = p.replies ?? prev.replies;
        updated++;
      }
      continue;
    }

    byId.set(p.id, {
      id: p.id,
      url: p.url || null,
      author: p.authorHandle || null,
      text: String(p.text || '').slice(0, 320),
      topic: p.topic || null,
      ageMinutes: p.ageMinutes ?? null,
      likes: p.likes ?? 0,
      replies: p.replies ?? 0,
      firstAt: now,
      lastAt: now,
      firstScore: score,
      lastScore: score,
    });
    fresh++;
  }

  let all = [...byId.values()].filter((o) => now - o.firstAt <= keepMs);
  if (all.length > MAX_OBSERVATIONS) {
    all.sort((a, b) => b.lastAt - a.lastAt);
    all = all.slice(0, MAX_OBSERVATIONS);
  }

  state.observations = all;
  return { total: all.length, fresh, updated };
}


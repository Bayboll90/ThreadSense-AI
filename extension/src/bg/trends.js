/**
 * Превратить тренд в материал той же формы, что отдаёт `collectNews`.
 *
 * Форма общая намеренно: генератору всё равно, откуда пришёл повод, и ни один
 * промпт от этого не меняется.
 *
 * **Что изменилось после первых боевых поводов.** Сперва материал строился
 * вокруг слова: «В ленте обсуждают: модель». Модель написала по такому поводу
 * ровно то, что можно написать про слово, — общие рассуждения. Слово само по
 * себе не событие, и повода в нём нет.
 *
 * Теперь материал строится вокруг **самого разогнавшегося поста**: вот что
 * человек написал, вот сколько это собрало и как быстро. Термин остаётся
 * ярлыком темы, но заголовком становится конкретная реплика, на которую есть
 * что ответить. Разница та же, что между «обсуждают нейросети» и «человек
 * пишет, что LLM это не интеллект, а математика, и за час собрал тридцать
 * реакций».
 */
export function trendsAsMaterial(trends, { now = Date.now() } = {}) {
  return trends.map((t) => {
    const ranked = [...t.sample].sort((a, b) => velocityOf(b, now) - velocityOf(a, now));
    const lead = ranked[0];
    const leadText = String(lead?.text || '').replace(/\s+/g, ' ').trim();

    /* Остальные реплики — контекст: они показывают, что тема не одиночная. */
    const others = ranked.slice(1)
      .map((p) => String(p.text || '').replace(/\s+/g, ' ').trim().slice(0, 200))
      .filter((s) => s.length > 30);

    const v = lead ? Math.round(velocityOf(lead, now)) : 0;

    return {
      id: `trend:${t.term}`,
      /*
       * Заголовок — сама реплика, а не ярлык. Именно он уходит в промпт как
       * «что произошло», и модель пишет о конкретном, а не о категории.
       */
      title: leadText
        ? `В ленте разошлось: «${leadText.slice(0, 180)}»`
        : `В ленте обсуждают: ${t.term}`,
      summary: [
        `Тема: ${t.term}. За окно — ${t.posts} постов у ${t.authors} авторов, ` +
        `рост в ${t.burst.toFixed(1)} раза к предыдущему.`,
        v > 0 ? `Самый быстрый пост набирает около ${v} реакций в час.` : '',
        t.replyRate > 0.35
          ? 'Люди отвечают, а не просто лайкают — значит в обсуждении есть место для своей мысли.'
          : 'Реагируют в основном лайками, разговора пока мало.',
        others.length ? '\nО чём ещё пишут по этой теме:' : '',
        ...others.map((q) => `— ${q}`),
        '',
        'Пиши не пересказ этой реплики, а своё: с чем не согласен, что здесь '
        + 'упускают, что знаешь из практики.',
      ].filter(Boolean).join('\n'),
      url: lead?.url || '',
      publishedAt: now,
      sourceId: 'threads-trend',
      sourceName: 'лента Threads',
      /* Первый уровень: это не чужая новость, а разговор, идущий прямо сейчас
         среди тех, кто нас может увидеть. */
      tier: 1,
      score: t.score,
      trend: {
        term: t.term, burst: t.burst, heat: t.heat, replyRate: t.replyRate, velocity: v,
      },
    };
  });
}

/**
 * Что залетает прямо сейчас — безотносительно тем.
 *
 * Отдельно от `detectTrends`, потому что отвечает на другой вопрос. Тренд — это
 * «о чём говорят многие»; здесь — «что выстрелило», пусть даже в одном посте и
 * без всякой темы вокруг. Владелец спрашивал именно про второе, и это разные
 * вещи: одиночный пост, собравший триста реакций за час, темой не станет
 * никогда (нет ни трёх постов, ни трёх авторов), а посмотреть на него надо.
 *
 * Применение — не повод для поста, а материал для разбора: по этому списку
 * видно, какие формулировки и форматы сейчас работают.
 */
export function risingPosts(state, settings, { now = Date.now(), limit = 8 } = {}) {
  const cfg = settings?.trends || {};
  const maxAgeH = cfg.risingMaxAgeHours ?? 24;

  return (state.observations || [])
    .filter((o) => {
      const publishedAt = o.firstAt - (o.ageMinutes ?? 0) * 60000;
      return now - publishedAt <= maxAgeH * 3.6e6 && (o.text || '').length > 40;
    })
    .map((o) => ({ ...o, velocity: velocityOf(o, now) }))
    .filter((o) => Number.isFinite(o.velocity) && o.velocity > 0)
    .sort((a, b) => b.velocity - a.velocity)
    .slice(0, limit);
}

/**
 * Поисковые фразы, выведенные из трендов.
 *
 * Замкнутая петля: агент ищет по тому, что уже разгорелось, находит там ещё
 * посты той же темы и уточняет оценку. Ровно так тема и не пропускается —
 * прежде набор запросов был зафиксирован в настройках навсегда и не знал
 * ничего о том, что сегодня происходит.
 *
 * Своих фраз из настроек это не отменяет: они держат нишу, чтобы петля не
 * увела агента в чужую тему, случайно вспыхнувшую в выборке.
 */
export function trendQueries(trends, settings, limit = 6) {
  const base = settings?.niche?.searchQueries || [];
  const known = new Set(base.map((q) => normalize(q)));

  const picked = [];
  for (const t of trends) {
    const q = t.term.trim();
    // Одно слово из четырёх букв — слишком общий запрос, выдача будет ни о чём.
    if (q.length < 5 && !q.includes(' ')) continue;
    if (known.has(normalize(q))) continue;
    picked.push(q);
    if (picked.length >= limit) break;
  }
  return picked;
}

/* ------------------------------------------------------------------ *
 * Здоровье поисковых фраз
 *
 * Проверка живым браузером 01.08: из двадцати двух фраз в настройках
 * **тринадцать не находят ничего вообще**. «mcp сервер», «ии агент», «промпт
 * инжиниринг», «скиллы claude» — ноль карточек, пустая страница. Поиск при
 * этом занимает почти половину заходов, то есть примерно каждая пятая сессия
 * агента уходила на то, чтобы перейти на пустую страницу, полистать её и уйти
 * на перерыв.
 *
 * В журнале это выглядело как «пустой скан, листаем дальше» — сообщение, по
 * которому невозможно отличить неудачный час от неработающей фразы. Ровно та
 * же болезнь, что и у прочих записей про молчание: агент не врал, но и не
 * называл причину.
 *
 * Список фраз при этом поправлен, и всё же механика нужна отдельно: выдача
 * Threads меняется, фраза, работавшая вчера, завтра может опустеть, а
 * поддерживать список руками никто не будет.
 * ------------------------------------------------------------------ */

/** Сколько пустых подряд, чтобы отложить фразу. */
const EMPTY_STREAK = 3;
/** На сколько откладываем. Сутки: за это время выдача успевает измениться. */
const BENCH_MS = 24 * 3.6e6;

/**
 * Запомнить, чем кончился скан по фразе.
 *
 * Считается серия подряд, а не общая доля: фраза, дающая посты через раз,
 * рабочая, а фраза, молчащая третий раз кряду, сломана. Любая находка серию
 * обнуляет — иначе временная тишина хоронила бы фразу навсегда.
 */
export function noteQueryResult(state, query, found, now = Date.now()) {
  if (!query) return null;
  const stats = { ...(state.queryStats || {}) };
  const e = { tries: 0, empty: 0, streak: 0, ...(stats[query] || {}) };

  e.tries++;
  e.lastAt = now;
  if (found > 0) {
    e.streak = 0;
    e.benchedAt = 0;
  } else {
    e.empty++;
    e.streak++;
    if (e.streak >= EMPTY_STREAK && !e.benchedAt) e.benchedAt = now;
  }

  stats[query] = e;
  state.queryStats = stats;
  return e;
}

/**
 * Фразы, которые имеет смысл пробовать.
 *
 * Если отложены все до единой — возвращаем полный список. Агент без единого
 * источника хуже агента с плохим источником, а массовое обнуление скорее
 * означает поломку разбора страницы, чем то, что в нише не осталось тем.
 */
export function healthyQueries(state, queries, now = Date.now()) {
  const stats = state?.queryStats || {};
  const ok = (queries || []).filter((q) => {
    const e = stats[q];
    if (!e?.benchedAt) return true;
    return now - e.benchedAt > BENCH_MS;
  });
  return ok.length ? ok : (queries || []);
}

/** Какие фразы сейчас отложены — для журнала и настроек. */
export function benchedQueries(state, now = Date.now()) {
  const stats = state?.queryStats || {};
  return Object.entries(stats)
    .filter(([, e]) => e.benchedAt && now - e.benchedAt <= BENCH_MS)
    .map(([q, e]) => `${q} (${e.streak} пустых подряд)`);
}

/** Сводка для журнала и интерфейса. */
export function trendSummary(trends) {
  if (!trends.length) return 'тем пока не видно';
  return trends.slice(0, 5)
    .map((t) => `${t.term} (×${t.burst.toFixed(1)}, ${t.posts}п)`)
    .join(' · ');
}

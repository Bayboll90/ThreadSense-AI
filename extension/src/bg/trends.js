/**
 * Насколько тема называет предмет, а не область.
 *
 * Первые боевые тренды выглядели так: «модель», «тредс», «проекты». Формально
 * всё верно — эти слова действительно разгорались, — но повод из них выходит
 * никакой: пост «в ленте обсуждают модель» не сообщает ничего. Владелец
 * попросил темы поинтереснее, и просьба справедливая.
 *
 * Что отличает хорошую тему от общего слова:
 *
 * - **Пара слов вместо одного.** «контекстное окно», «claude code», «агенты
 *   openai» называют предмет; «окно», «code», «агенты» — только область.
 * - **Имя собственное.** Latin-токены и версии — это названия продуктов и
 *   релизов: `astra`, `seedance`, `codex`, `gpt`. Именно они и есть события,
 *   о которых стоит писать.
 * - **Длина.** Короткое русское слово почти всегда общее.
 *
 * Множитель, а не фильтр: общее слово с огромным всплеском всё-таки может
 * оказаться настоящей новостью, и запрещать его насовсем неправильно.
 */
export function specificity(term) {
  const words = term.split(' ');
  let k = 1;

  if (words.length > 1) k *= 1.6;                       // пара называет предмет
  if (/[a-z]/i.test(term)) k *= 1.25;                   // имя продукта, а не область
  if (/\d/.test(term)) k *= 1.15;                       // версия: «5.6», «seedance 2»
  if (words.length === 1 && term.length <= 6) k *= 0.7; // короткое одиночное — общее

  return k;
}

/**
 * Тема обязана быть темой **нашей ниши**, а не просто разогнавшимся словом.
 *
 * Поймано в бою 02.08, и цена оказалась двойной. Верхушку трендов заняли
 * «сначала» (×9 всплеск), «автор», «одного», «людей» — обычные русские слова,
 * которые прошли всё: и стоп-лист, и порог в три автора, и долю ленты. Из них
 * агент сделал повод для поста и опубликовал «Threads разгоняет тему
 * "сначала"», а следом эти же слова уехали в поисковые фразы — в статистике
 * запросов стоят `сначала`, `автор`, `одного`, `каждый`. То есть агент искал
 * цели для комментариев по слову «сначала» и приносил из выдачи ленту не по
 * теме, которую сам же потом складывал в наблюдения. Петля.
 *
 * Список стоп-слов эту породу не ловит и поймать не может: перечислять все
 * формы всех общих слов языка — гонка без финиша, и каждый прогон добавлял в
 * список новую партию («которая», «впервые», «июль»…).
 *
 * Здесь проверка идёт с другой стороны: не «это слово мусорное?», а «это слово
 * вообще про то, чем мы занимаемся?». Ответ уже есть в настройках — корни
 * ключевых слов ниши, по которым работает префильтр. Латиница и цифры
 * пропускаются отдельно: названия продуктов и версий в списке корней стоять не
 * обязаны, а именно они и есть события ниши.
 *
 * Проверено на 400 боевых наблюдениях: правило убирает ровно «сначала»,
 * «автор», «одного», «людей» и не трогает ни одной настоящей темы —
 * «промптов», «нейросеть», «chatgpt», «claude» остаются на местах.
 */
export function nicheRelevant(term, settings) {
  const roots = (settings?.niche?.includeKeywords || [])
    .map((k) => String(k).trim().toLowerCase())
    .filter((k) => k.length >= 3);

  /* Пустой список корней — это «мы не знаем ниши», а не «ничего не подходит».
     Проверка, у которой нет данных, обязана пропускать, а не запрещать всё. */
  if (!roots.length) return true;

  /* Пары слов проходят по любому своему слову: в «контекстное окно» нишевым
     является второе, в «claude уровня» — первое. */
  return term.split(' ').some((w) => /[a-z0-9]/i.test(w) || roots.some((r) => w.includes(r)));
}

/**
 * Сглаживание при сравнении долей.
 *
 * Без него слово, встретившееся впервые, даёт деление на ноль и уносит всю
 * верхушку списка. Величина подобрана так, чтобы тема, занимающая меньше
 * процента свежего окна, не могла выиграть только за счёт новизны.
 */
const ALPHA = 0.01;

/**
 * Что обсуждают сейчас.
 *
 * @returns {Array<{term, heat, burst, score, posts, sample, replyRate}>}
 */
export function detectTrends(state, settings, now = Date.now()) {
  const cfg = settings?.trends || {};
  const hotH = cfg.hotHours ?? 8;
  const minPosts = cfg.minPostsPerTrend ?? 3;
  const obs = state.observations || [];
  if (obs.length < (cfg.minObservations ?? 12)) return [];

  const hotEdge = now - hotH * 3.6e6;

  /** term -> { hot, base, posts[] } */
  const acc = new Map();
  let hotTotal = 0;
  let baseTotal = 0;
  let hotPosts = 0;

  for (const o of obs) {
    const v = velocityOf(o, now);
    if (!Number.isFinite(v) || v <= 0) continue;

    // К свежему окну пост относится по времени своей публикации, а не по
    // времени, когда мы его увидели: увиденное вчера могло быть написано час
    // назад, и наоборот.
    const publishedAt = o.firstAt - (o.ageMinutes ?? 0) * 60000;
    const isHot = publishedAt >= hotEdge;

    if (isHot) { hotTotal += v; hotPosts++; } else baseTotal += v;

    for (const t of termsOf(o.text)) {
      let e = acc.get(t);
      if (!e) { e = { hot: 0, base: 0, posts: [] }; acc.set(t, e); }
      if (isHot) { e.hot += v; e.posts.push(o); } else { e.base += v; }
    }
  }

  if (hotTotal <= 0) return [];

  const out = [];
  for (const [term, e] of acc) {
    if (e.posts.length < minPosts) continue;

    const shareHot = e.hot / hotTotal;
    const shareBase = baseTotal > 0 ? e.base / baseTotal : 0;
    const burst = (shareHot + ALPHA) / (shareBase + ALPHA);

    /*
     * Жар берётся логарифмом. В линейной шкале одна вирусная ветка делает
     * своё случайное слово главной темой ниши — ровно та ошибка, о которой
     * записано в уроках про верхушку выдачи: цифра большая, явление не то.
     */
    const score = Math.log1p(e.hot) * Math.min(6, burst) * specificity(term);

    // Сколько разговора, а не одобрения: тема, где отвечают, даёт нам место.
    const likes = e.posts.reduce((s, p) => s + (p.likes || 0), 0);
    const replies = e.posts.reduce((s, p) => s + (p.replies || 0), 0);

    out.push({
      term,
      heat: Math.round(e.hot * 10) / 10,
      burst: Math.round(burst * 100) / 100,
      score: Math.round(score * 100) / 100,
      posts: e.posts.length,
      authors: new Set(e.posts.map((p) => p.author)).size,
      replyRate: likes + replies > 0 ? replies / (likes + replies) : 0,
      sample: [...e.posts]
        .sort((a, b) => velocityOf(b, now) - velocityOf(a, now))
        .slice(0, 4),
    });
  }

  /*
   * Тема, о которой пишет один человек, — не тема, а автор. Порог по числу
   * разных авторов отсекает и серию постов одного блогера, и наши собственные
   * тексты, отражённые лентой.
   *
   * Порог поднят с двух до трёх после прогона на 243 живых постах: при двух
   * половину верхушки занимали слова, случайно попавшие в пару соседних
   * текстов — «неделю», «подписки», «впервые», «июль». Два совпадения это ещё
   * совпадение; тема начинается с третьего.
   */
  const minAuthors = cfg.minAuthors ?? 3;

  /*
   * Слово, которое встречается почти везде, темой не является, каким бы
   * горячим ни выглядело. В нишевой ленте это сама ниша: «нейросети» стоят в
   * каждом втором посте, и писать «в ленте обсуждают нейросети» бессмысленно.
   *
   * Порог применяется только когда наблюдений достаточно, чтобы доля вообще
   * что-то значила. На дюжине записей четверть — это три поста, то есть ровно
   * тот объём, с которого тема только начинается; отсекать по нему значит
   * запрещать всё новое, пока лента не наберётся. Поймано тестом, где новая
   * тема шла четвёртой из двенадцати и исчезала из выдачи.
   */
  /*
   * Доля считается от свежего окна, а не от всех наблюдений, — иначе порог
   * сравнивает несравнимое. `t.posts` — это посты **горячего** окна, в котором
   * тема встретилась; при сорока восьми часах хранения и восьми часах «сейчас»
   * их в разы меньше, чем наблюдений всего. Порог в четверть от четырёхсот
   * записей означал «тема должна стоять в сотне свежих постов» — столько их в
   * окне не бывает вовсе, и защита от вездесущего слова не срабатывала ни разу.
   */
  const enoughForShare = obs.length >= (cfg.minObsForShare ?? 40);
  const ubiquitous = enoughForShare && hotPosts > 0
    ? Math.max(3, Math.round(hotPosts * (cfg.maxShareOfFeed ?? 0.25)))
    : Infinity;

  return out
    .filter((t) => t.authors >= minAuthors && t.posts <= ubiquitous)
    .filter((t) => nicheRelevant(t.term, settings))
    .sort((a, b) => b.score - a.score)
    .slice(0, cfg.topN ?? 12);
}

/**
 * Убрать темы, поглощённые более точными.
 *
 * «claude» и «claude code» почти всегда всплывают вместе, и без этого шага
 * список трендов наполовину состоит из огрызков одной темы. Побеждает пара:
 * она называет предмет разговора, а одиночное слово — только его область.
 */
export function dedupeTrends(trends) {
  const out = [];
  for (const t of trends) {
    const covered = out.some((k) => k.term.includes(t.term) || t.term.includes(k.term));
    if (!covered) out.push(t);
  }
  return out;
}


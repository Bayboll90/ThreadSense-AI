/**
 * @param {string} retryNote чем не подошла прошлая попытка. Пустая строка на
 *        первом заходе. Без этой строки повтор — тот же промпт с чуть иным
 *        разбросом, то есть та же ошибка второй раз; на моделях 5.6 разброса
 *        нет вовсе, потому что температура зафиксирована платформой.
 */
export function writeUser(thread, analysis, angle, settings, retryNote = '', length = null) {
  const { root, replies = [] } = thread;
  const target = analysis?.reply_to != null ? replies[analysis.reply_to] : null;
  const st = settings.style;

  const parts = [];

  parts.push(`ПОСТ от @${root.authorHandle || '?'}:`);
  parts.push(clip(root.text, 1400));

  if (replies.length) {
    parts.push('');
    parts.push('ЧТО УЖЕ НАПИСАЛИ В ВЕТКЕ:');
    parts.push(replies.slice(0, 8).map((r, i) =>
      `[${i}] @${r.authorHandle || '?'}: ${clip(r.text, 240)}`).join('\n'));
  }

  parts.push('');
  if (target) {
    parts.push(`ТЫ ОТВЕЧАЕШЬ НА КОММЕНТАРИЙ [${analysis.reply_to}] от @${target.authorHandle || '?'}:`);
    parts.push(`«${clip(target.text, 400)}»`);
    parts.push('Обращайся к автору этого комментария, а не к автору поста. Имя писать не нужно.');
  } else {
    parts.push('ТЫ ОТВЕЧАЕШЬ САМОМУ ПОСТУ.');
  }

  if (analysis?.gap) {
    parts.push('');
    parts.push(`ЧЕГО В ОБСУЖДЕНИИ НЕ ХВАТАЕТ (оттолкнись именно от этого):\n${analysis.gap}`);
  }

  const a = ANGLES[angle];
  if (a) {
    parts.push('');
    parts.push(`УГОЛ ЗАХОДА — ${a.label}: ${a.hint}`);
  }

  if (analysis?.do_not_say?.length) {
    parts.push('');
    parts.push(`УЖЕ СКАЗАНО, НЕ ПОВТОРЯЙ:\n${analysis.do_not_say.map((x) => `- ${x}`).join('\n')}`);
  }

  if (st.examples?.length) {
    parts.push('');
    parts.push('ПРИМЕРЫ МОИХ РЕАЛЬНЫХ КОММЕНТАРИЕВ (копируй ритм и тон, не содержание):');
    parts.push(pickExamples(st.examples, 6).map((e) => `— ${clip(e, 200)}`).join('\n'));
  }

  if (retryNote) {
    parts.push('');
    parts.push(`ПРЕДЫДУЩАЯ ПОПЫТКА НЕ ПРОШЛА: ${retryNote}`);
    parts.push('Напиши заново с учётом этого. Не повторяй прежнюю формулировку.');
  }

  parts.push('');
  const len = length || rollLength(st);
  parts.push(`Напиши один комментарий. ${len.min}-${len.max} символов. Только текст.`);

  return parts.join('\n');
}


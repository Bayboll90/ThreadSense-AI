/**
 * Все промпты в одном месте.
 *
 * Ключевые решения по качеству, которые здесь зашиты:
 *
 * 1. Модели никогда не даётся задача «напиши комментарий к посту». Сначала
 *    отдельным дешёвым проходом она разбирает ветку и формулирует gap — чего в
 *    обсуждении не хватает. Без этого шага на выходе всегда получается вежливое
 *    «согласен, отличная мысль», потому что это статистически самый безопасный
 *    ответ на любой текст.
 *
 * 2. Модель не просят «писать с ошибками». Она делает это карикатурно.
 *    Опечатки добавляет отдельный локальный слой (humanizer.js), а промпт
 *    отвечает только за содержание, тон и ритм.
 *
 * 3. Запреты формулируются списком конкретных фраз, а не «пиши естественно».
 *    Абстрактная инструкция игнорируется, конкретный чёрный список работает.
 */

import { ANGLES } from '../common/defaults.js';
import { weightedPick, randInt } from '../common/rng.js';

/* ------------------------------------------------------------------ *
 * Длина реплики разыгрывается, а не задаётся
 *
 * Прежде в промпте стояло «25-220 символов, целиться в 120», и модель
 * послушно целилась: почти все комментарии выходили в 100-220 знаков.
 * Одинаковая длина — такой же признак одного автора-программы, как
 * одинаковые интервалы между действиями, и заметен он даже проще: длину
 * видно глазом, без всякой телеметрии.
 *
 * Живой человек отвечает неровно. Чаще всего — парой фраз, иногда бросает
 * три слова в согласие, изредка расписывает случай из работы. Веса взяты
 * из замера 485 живых реплик в ветках ниши 01.08: реплики короче сорока
 * символов получают ответ в 34% случаев против средних 44%, то есть
 * короткие уместны, но не должны становиться основным форматом.
 * ------------------------------------------------------------------ */

const LENGTH_MOODS = {
  short: { weight: 20, label: 'короткая реплика в одну фразу' },
  normal: { weight: 55, label: 'обычная реплика в две-три фразы' },
  long: { weight: 25, label: 'развёрнутая реплика с примером' },
};

/**
 * Какой длины писать этот конкретный комментарий.
 * @returns {{min: number, max: number, target: number, label: string}}
 */
export function rollLength(st) {
  const mix = st.lengthMix || {};
  const mood = weightedPick(
    Object.entries(LENGTH_MOODS).map(([key, m]) => [key, mix[key] ?? m.weight]),
  );

  const floor = Math.max(20, st.minLen || 25);
  const ceil = Math.max(floor + 20, st.maxLen || 220);
  const mid = Math.min(Math.max(st.targetLen || 120, floor + 10), ceil - 10);

  if (mood === 'short') {
    return { min: floor, max: Math.round(mid * 0.6), target: randInt(floor + 10, Math.round(mid * 0.55)), label: LENGTH_MOODS.short.label };
  }
  if (mood === 'long') {
    return { min: Math.round(mid * 1.1), max: ceil, target: randInt(Math.round(mid * 1.2), ceil - 10), label: LENGTH_MOODS.long.label };
  }
  return { min: Math.round(mid * 0.6), max: Math.round(mid * 1.3), target: randInt(Math.round(mid * 0.7), Math.round(mid * 1.2)), label: LENGTH_MOODS.normal.label };
}


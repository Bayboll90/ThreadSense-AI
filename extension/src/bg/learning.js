/**
 * Агент учится на своих результатах.
 *
 * До 02.08 веса форматов настраивались одним способом: я собирал выборку чужих
 * постов, считал, что в ней работает, и вписывал числа в `POST_KINDS`. Способ
 * рабочий, но у него два изъяна, и оба неустранимы изнутри.
 *
 * Первый: он измеряет **чужие** посты. Что работает у аккаунта с тысячей
 * читателей, не обязано работать у аккаунта с девятнадцатью, и наоборот.
 * Второй: он требует меня. Ниша меняется, а числа остаются те же до
 * следующего раза, когда кто-нибудь сядет и пересчитает.
 *
 * Здесь замыкается петля: агент публикует, через час-другой смотрит, что из
 * этого вышло, и сам подкручивает, каких форматов делать больше.
 *
 * ─────────────────────────────────────────────────────────────────────
 *
 * ЧТО СЧИТАЕТСЯ УСПЕХОМ
 *
 * Не число реакций, а факт: **пришла ли на пост хоть одна чужая реакция.**
 *
 * Причина в форме данных. Отклик у нас редкий и с тяжёлым хвостом: девятнадцать
 * постов из двадцати собирают ноль, двадцатый — сорок. Среднее по такой
 * выборке скачет от одного поста и ничего не говорит о формате. Доля же
 * «хоть что-то пришло» — обычная бернуллиевская величина, у неё известная
 * дисперсия и она устойчива на десятке наблюдений.
 *
 * Тот же выбор мы уже сделали руками при разборе комментариев: там доля
 * получивших ответ оказалась информативнее средних, и по ней принимались
 * решения.
 *
 * ЧТО ДЕЛАЕТСЯ С МАЛОЙ ВЫБОРКОЙ
 *
 * Три поста формата «грабли», из них один с откликом — это не «33% успеха»,
 * это «мы почти ничего не знаем». Поэтому оценка не берётся напрямую, а
 * сглаживается к общей доле по всем постам:
 *
 *     p = (успехи + α₀ · p_общая) / (наблюдения + α₀)
 *
 * Это апостериорное среднее бета-биномиальной модели с априорной силой α₀.
 * При нуле наблюдений оценка равна общей доле, при большом числе — своей
 * собственной. α₀ = 8 означает: чтобы сдвинуть оценку формата наполовину к
 * его фактической доле, нужно восемь его постов.
 *
 * ЧТО ДЕЛАЕТСЯ СО СТАРЫМИ ДАННЫМИ
 *
 * Наблюдение месячной давности говорит о нише, которой уже нет. Каждое
 * взвешивается экспоненциальным затуханием по возрасту с постоянной
 * `halfLifeDays`: пост недельной давности при периоде полураспада в неделю
 * весит вдвое меньше вчерашнего.
 *
 * ПОЧЕМУ МНОЖИТЕЛЬ, А НЕ ЗАМЕНА ВЕСОВ
 *
 * Веса в `POST_KINDS` несут не только «что заходит», но и редакторское
 * решение: профиль не должен состоять из одних вопросов, даже если вопросы
 * заходят лучше всего. Замена весов данными стёрла бы это.
 *
 * Поэтому данные лишь наклоняют заданное:
 *
 *     множитель = clamp((p_формата / p_общая)^γ, 1/K, K)
 *
 * Степень γ < 1 гасит перекос (при γ = 0.7 двукратное преимущество даёт
 * прибавку в 1.6 раза), а границы гарантируют, что ни один формат не исчезнет
 * и ни один не займёт всё. Это же и есть механизм исследования: формат,
 * которому не повезло на первых трёх постах, сохраняет половину прежнего веса
 * и обязательно получит новые попытки.
 *
 * ─────────────────────────────────────────────────────────────────────
 *
 * Все функции чистые и работают с обычным объектом состояния: математику здесь
 * можно и нужно гонять симуляцией, а не проверять в бою.
 */

import { normalize } from '../common/text.js';

/** Сколько записей о своих постах держим. */
const MAX_POSTS = 200;

/* ------------------------------------------------------------------ *
 * Сбор
 * ------------------------------------------------------------------ */

/**
 * Запомнить только что опубликованный пост.
 *
 * Адреса у нас в этот момент нет: композер публикует и закрывается, ссылку
 * Threads не отдаёт. Поэтому запись опознаётся позже по началу текста — оно
 * уникально с запасом, а защита от самоповтора этого и добивается.
 */
export function recordPost(state, { kind, topic, parts, text }, now = Date.now()) {
  const all = Array.isArray(parts) && parts.length ? parts : [text];
  const first = String(all[0] || '').trim();
  if (!first) return state;

  const rec = {
    kind,
    topic: topic || null,
    parts: all.length,
    len: first.length,
    key: normalize(first).slice(0, 60),
    publishedAt: now,
    /* Пока не измерено — null, а не ноль: «мы не смотрели» и «посмотрели, там
       пусто» это разные утверждения, и путать их значит учиться на выдумке. */
    likes: null,
    replies: null,
    measuredAt: null,
  };

  state.myPosts = [...(state.myPosts || []), rec].slice(-MAX_POSTS);
  return state;
}

/**
 * Сопоставить карточки своего профиля с записями и снять счётчики.
 *
 * Вызывается на том же скане профиля, который агент делает ради ответов своим
 * читателям, — отдельного обхода не нужно.
 *
 * **Части ветки вычитаются.** У корня многочастной ветки в счётчике ответов
 * лежат и наши собственные продолжения. Не вычесть их значит записать себе в
 * успех разговор с самим собой, а формат «разбор» из трёх частей выглядел бы
 * втрое успешнее одиночного поста при нулевом внешнем отклике.
 *
 * @returns {{matched: number, updated: number}}
 */
export function measurePosts(state, cards, settings, now = Date.now()) {
  const posts = state.myPosts || [];
  if (!posts.length) return { matched: 0, updated: 0 };

  const minAgeMs = (settings?.learning?.minAgeHours ?? 2) * 3.6e6;
  let matched = 0;
  let updated = 0;

  for (const c of cards || []) {
    const key = normalize(c.text || '').slice(0, 60);
    if (!key) continue;

    const rec = posts.find((p) => p.key && (p.key === key || key.startsWith(p.key)));
    if (!rec) continue;
    matched++;

    /*
     * Слишком свежий пост не измеряем вовсе. Ноль реакций через пять минут
     * после публикации — это не результат формата, это отсутствие времени.
     */
    if (now - rec.publishedAt < minAgeMs) continue;

    const own = Math.max(0, (rec.parts || 1) - 1);
    const replies = Math.max(0, (c.replies || 0) - own);
    const likes = Math.max(0, c.likes || 0);

    /* Счётчики не убывают: меньшее значение означает, что число не
       прочиталось, а не что реакции сняли. Тот же принцип, что в наблюдениях. */
    if (rec.measuredAt && likes < (rec.likes ?? 0) && replies < (rec.replies ?? 0)) continue;

    rec.likes = Math.max(rec.likes ?? 0, likes);
    rec.replies = Math.max(rec.replies ?? 0, replies);
    rec.measuredAt = now;
    updated++;
  }

  return { matched, updated };
}

/* ------------------------------------------------------------------ *
 * Математика
 * ------------------------------------------------------------------ */

/** Успех — факт чужой реакции, а не её величина. См. заголовок файла. */
export function isHit(rec) {
  return (rec.likes || 0) > 0 || (rec.replies || 0) > 0;
}

/** Вес наблюдения по возрасту: экспоненциальное затухание. */
export function ageWeight(rec, settings, now = Date.now()) {
  const half = Math.max(0.5, settings?.learning?.halfLifeDays ?? 7);
  const days = Math.max(0, (now - rec.publishedAt) / 864e5);
  return Math.pow(0.5, days / half);
}

/**
 * Сводка по форматам: сколько наблюдений, сколько попаданий, сглаженная доля.
 *
 * Возвращает и общую долю: она же априорное среднее, и без неё нельзя ни
 * сгладить оценку формата, ни посчитать множитель.
 */
export function formatStats(state, settings, now = Date.now()) {
  const measured = (state.myPosts || []).filter((p) => p.measuredAt);

  let totalN = 0;
  let totalHits = 0;
  const byKind = {};

  for (const rec of measured) {
    const w = ageWeight(rec, settings, now);
    const hit = isHit(rec) ? w : 0;

    totalN += w;
    totalHits += hit;

    const k = (byKind[rec.kind] ||= { n: 0, hits: 0, posts: 0 });
    k.n += w;
    k.hits += hit;
    k.posts++;
  }

  const base = totalN > 0 ? totalHits / totalN : 0;
  const alpha = Math.max(0.1, settings?.learning?.priorStrength ?? 8);

  for (const [kind, k] of Object.entries(byKind)) {
    /* Апостериорное среднее бета-биномиальной модели: своя доля,
       подтянутая к общей тем сильнее, чем меньше наблюдений. */
    k.rate = (k.hits + alpha * base) / (k.n + alpha);
    k.raw = k.n > 0 ? k.hits / k.n : null;
    byKind[kind] = k;
  }

  return { base, totalN, totalPosts: measured.length, byKind };
}

/**
 * Множитель веса формата.
 *
 * Единица означает «данных нет либо формат ровно средний». Границы жёсткие:
 * ни один формат не исчезает и ни один не забирает всё — это и есть
 * встроенное исследование.
 */
export function learnedFactor(kind, stats, settings) {
  const cfg = settings?.learning || {};
  if (!cfg.enabled) return 1;

  /* Пока измеренных постов мало, любые различия между форматами — шум. */
  if (stats.totalPosts < (cfg.minPosts ?? 12)) return 1;
  if (!stats.base) return 1;

  const k = stats.byKind[kind];
  if (!k) return 1;

  const gamma = cfg.damping ?? 0.7;
  const cap = Math.max(1.01, cfg.maxShift ?? 2);

  const ratio = k.rate / stats.base;
  const shifted = Math.pow(ratio, gamma);
  return Math.min(cap, Math.max(1 / cap, shifted));
}

/**
 * Что агент выучил — строкой для журнала.
 *
 * Обучение, которого не видно, неотличимо от его отсутствия: по молчаливо
 * изменившимся весам нельзя понять ни что происходит, ни когда пора
 * вмешаться. Здесь тот же принцип, что и у прочих записей в журнале.
 */
export function learningReport(state, settings, now = Date.now()) {
  const stats = formatStats(state, settings, now);
  if (!stats.totalPosts) return 'измеренных постов пока нет';

  const rows = Object.entries(stats.byKind)
    .map(([kind, k]) => ({ kind, k, f: learnedFactor(kind, stats, settings) }))
    .sort((a, b) => b.f - a.f);

  const head = `измерено ${stats.totalPosts} постов, отклик у ${(stats.base * 100).toFixed(0)}%`;
  if (stats.totalPosts < (settings?.learning?.minPosts ?? 12)) {
    return `${head} — мало для выводов, веса не трогаем`;
  }

  const body = rows
    .map(({ kind, k, f }) => `${kind} ×${f.toFixed(2)} (${Math.round(k.hits)}/${k.posts})`)
    .join(' · ');

  return `${head}. ${body}`;
}

/**
 * Возможности модели, включая незнакомые.
 *
 * Список выше перечисляет то, что проверено вживую. Модель, которой в нём нет,
 * может быть и новее нашего кода — поэтому семейство 5.6 и всё, что старше,
 * считается не принимающим сэмплирующие параметры: это поведение новых
 * линеек, а ошибиться в эту сторону дешевле. Незнакомое имя без версии
 * трактуется как классическое — так вёл себя весь парк до 5.6.
 */
export function traitsOf(model) {
  const known = MODEL_TRAITS[model];
  if (known) return known;

  const m = /^gpt-(\d+)\.(\d+)/.exec(String(model || ''));
  if (m) {
    const major = Number(m[1]);
    const minor = Number(m[2]);
    if (major > 5 || (major === 5 && minor >= 6)) return NO_SAMPLING;
  }
  return CLASSIC;
}


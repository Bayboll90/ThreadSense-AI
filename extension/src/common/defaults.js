/**
 * Подтянуть сохранённые настройки к текущей схеме.
 *
 * Живёт здесь, а не в storage.js, по двум причинам: схема описана в этом файле,
 * и функция получается чистой — её можно проверить тестом, не поднимая
 * chrome.storage.
 *
 * Правило миграции одно: **трогаем только то, что человек не трогал сам.**
 * Сохранённые настройки перекрывают дефолты (см. deepMerge в getSettings),
 * поэтому смена дефолта сама по себе до работающей установки не доходит — но
 * это же означает, что миграция обязана отличать «осталось от старого дефолта»
 * от «выставлено руками». Сравнение со старым значением и решает: совпало —
 * человек этого поля не касался, можно обновлять.
 *
 * @param {object} s           уже слитые настройки
 * @param {number} fromVersion версия, с которой они пришли
 */
export function migrateSettings(s, fromVersion) {
  const version = Number(fromVersion) || 0;
  if (version < 4 && s.timing) {
    if (s.timing.activeFrom === 9 && s.timing.activeTo === 23) s.timing.activeTo = 1;
    if (Array.isArray(s.timing.circadian)
      && s.timing.circadian.length === 24
      && Number(s.timing.circadian[0]) === 0
      && Number(s.timing.circadian[23]) === 0.25) {
      s.timing.circadian[0] = DEFAULT_CIRCADIAN[0];
    }
  }
  if (version < 12 && s.posting?.graceMin === 25) s.posting.graceMin = 55;
  if (version < 13) {
    s.enabled = false;
    s.autopilot = false;
  }
  if (version < 14) {
    if (typeof s.ui?.overlay === 'boolean') s.ui.overlay = s.ui.overlay ? 'window' : 'off';
    if (!s.rhythm) s.rhythm = structuredCloneSafe(DEFAULTS.rhythm);
    if (!s.stealth) s.stealth = structuredCloneSafe(DEFAULTS.stealth);
  }
  if (version < 15) {
    if (!s.ai?.provider) s.ai.provider = 'openai';
    if (!s.ai?.protocol) s.ai.protocol = 'openai';
    if (!s.ai?.defaultPricing) s.ai.defaultPricing = { ...DEFAULTS.ai.defaultPricing };
    if (!s.ai?.promptOverrides) s.ai.promptOverrides = { ...DEFAULTS.ai.promptOverrides };
    if (s.funnel) {
      s.funnel.enabled = false;
      if (s.funnel.followup) s.funnel.followup.enabled = false;
    }
    if (s.tools) {
      s.tools.enabled = false;
      s.tools.registryEnabled = false;
      s.tools.githubQueries = [];
    }
    s.enabled = false;
    s.autopilot = false;
  }
  s.version = SCHEMA_VERSION;
  return s;
}

export function applyPreset(settings, presetName) {
  const p = PRESETS[presetName];
  if (!p) return settings;

  return {
    ...settings,
    preset: presetName,
    // Автопилот — часть режима, а не отдельная настройка: выбрал пресет,
    // значит согласился, что агент работает сам.
    autopilot: p.autopilot ?? settings.autopilot,
    limits: { ...settings.limits, ...p.limits },
    timing: { ...settings.timing, ...p.timing },
    scoring: { ...settings.scoring, ...p.scoring },
    filters: { ...settings.filters, ...p.filters },
    posting: { ...settings.posting, ...p.posting },
    safety: { ...settings.safety, ...p.safety },
    niche: {
      ...settings.niche,
      ...p.niche,
      // Веса источников — вложенный объект: подменять целиком нельзя, иначе
      // потеряются ключи, которых в пресете нет.
      sourceWeights: { ...settings.niche?.sourceWeights, ...p.niche?.sourceWeights },
    },
  };
}

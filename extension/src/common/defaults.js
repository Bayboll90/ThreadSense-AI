/** Глубокое слияние: значения из src перекрывают base, структура base ведущая. */
export function deepMerge(base, src) {
  if (Array.isArray(base)) return Array.isArray(src) ? src.slice() : base.slice();
  if (base && typeof base === 'object') {
    const out = {};
    for (const k of Object.keys(base)) {
      out[k] = k in (src || {}) ? deepMerge(base[k], src[k]) : structuredCloneSafe(base[k]);
    }
    // Ключи, которых нет в схеме, сохраняем — вдруг это пользовательские данные.
    for (const k of Object.keys(src || {})) if (!(k in out)) out[k] = src[k];
    return out;
  }
  return src === undefined ? base : src;
}

function structuredCloneSafe(v) {
  if (Array.isArray(v)) return v.slice();
  if (v && typeof v === 'object') return JSON.parse(JSON.stringify(v));
  return v;
}


/* ------------------------------------------------------------------ *
 * Что модель принимает в запросе.
 *
 * Линейка 5.6 не принимает ни один из сэмплирующих параметров: `top_p`,
 * `presence_penalty` и `frequency_penalty` отвергаются целиком, а
 * `temperature` — с любым значением, кроме 1. Послать их означает получить
 * 400 на каждом запросе, а у нас на 400 срабатывает каскад запасных моделей:
 * агент молча продолжил бы работать на старой модели, и в журнале это не
 * ошибка. Проверено живыми запросами 31.07.2026.
 *
 * `reasoning` — «подумать» перед ответом. У 5.6 включено по умолчанию и
 * оплачивается как выходные токены. При нашем `maxOutputTokens: 400` размышление
 * съедало весь лимит: в замере три поста из четырёх вернулись ПУСТЫМИ. Поэтому
 * effort гасится явно, а не оставляется на усмотрение модели.
 * ------------------------------------------------------------------ */
